#!/usr/bin/env node
/**
 * Command line front end for lib/youtubeCaptions.mjs.
 *
 * Extracts the captions / subtitles of a YouTube video and prints them as
 * plain text, SRT, WebVTT or JSON. No API key, no dependencies, Node 18+.
 *
 *   node scripts/youtube-captions.mjs <url|videoId> [options]
 *
 * The same core powers the /youtube/captions page in the site.
 */

import {
  CaptionError,
  FORMATS,
  fetchCaptions,
  fetchVideoInfo,
  formatCues,
} from '../lib/youtubeCaptions.mjs';

const USAGE = `
Extract YouTube video captions.

Usage
  node scripts/youtube-captions.mjs <url|videoId> [options]

Options
  -l, --lang <code>      Preferred caption language (default: en). Use "any"
                         to take the first available track.
  -f, --format <fmt>     txt | srt | vtt | json           (default: txt)
  -o, --out <file>       Write to a file instead of stdout
      --translate <code> Ask YouTube to machine-translate into this language
      --list             List the available caption tracks and exit
      --auto             Prefer auto-generated (ASR) captions
      --no-auto          Ignore auto-generated captions
      --timestamps       Prefix each line with [mm:ss] in txt output
  -h, --help             Show this message

Examples
  node scripts/youtube-captions.mjs https://youtu.be/dQw4w9WgXcQ
  node scripts/youtube-captions.mjs dQw4w9WgXcQ --list
  node scripts/youtube-captions.mjs <url> -l ar -f srt -o captions.srt
  node scripts/youtube-captions.mjs <url> --translate en --timestamps
`.trim();

function parseArgs(argv) {
  const opts = {
    target: null,
    lang: 'en',
    format: 'txt',
    out: null,
    translate: null,
    list: false,
    auto: null, // null = no preference, true = prefer ASR, false = exclude ASR
    timestamps: false,
    help: false,
  };

  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    const next = () => {
      const value = argv[++i];
      if (value === undefined) throw new Error(`Missing value for ${arg}`);
      return value;
    };

    switch (arg) {
      case '-h':
      case '--help':
        opts.help = true;
        break;
      case '-l':
      case '--lang':
        opts.lang = next();
        break;
      case '-f':
      case '--format':
        opts.format = next().toLowerCase();
        break;
      case '-o':
      case '--out':
        opts.out = next();
        break;
      case '--translate':
        opts.translate = next();
        break;
      case '--list':
        opts.list = true;
        break;
      case '--auto':
        opts.auto = true;
        break;
      case '--no-auto':
        opts.auto = false;
        break;
      case '--timestamps':
        opts.timestamps = true;
        break;
      default:
        if (arg.startsWith('-')) throw new Error(`Unknown option: ${arg}`);
        if (opts.target) throw new Error(`Unexpected argument: ${arg}`);
        opts.target = arg;
    }
  }

  return opts;
}

async function main() {
  const opts = parseArgs(process.argv.slice(2));

  if (opts.help || !opts.target) {
    console.log(USAGE);
    process.exit(opts.target ? 0 : 1);
  }

  if (!FORMATS.includes(opts.format)) {
    throw new Error(`Unknown format: ${opts.format}. Use ${FORMATS.join(', ')}.`);
  }

  if (opts.list) {
    const info = await fetchVideoInfo(opts.target);
    if (info.title) console.log(`${info.title}\n`);
    for (const track of info.tracks) {
      const flags = [track.auto ? 'auto-generated' : 'manual'];
      if (track.translatable) flags.push('translatable');
      console.log(`  ${track.lang.padEnd(8)} ${track.name}  (${flags.join(', ')})`);
    }
    return;
  }

  const result = await fetchCaptions(opts.target, opts);

  const wanted = opts.lang.toLowerCase();
  if (wanted !== 'any' && !opts.translate && !result.language.toLowerCase().startsWith(wanted)) {
    console.error(`No "${opts.lang}" captions on this video — falling back to "${result.language}".`);
  }

  const output = formatCues(result.cues, opts.format, {
    timestamps: opts.timestamps,
    meta: {
      videoId: result.videoId,
      title: result.title,
      channel: result.channel,
      language: result.language,
      autoGenerated: result.autoGenerated,
    },
  });

  if (opts.out) {
    const { writeFile } = await import('node:fs/promises');
    await writeFile(opts.out, `${output}\n`, 'utf8');
    console.error(`Wrote ${result.cues.length} caption lines to ${opts.out}`);
  } else {
    process.stdout.write(`${output}\n`);
  }
}

main().catch((error) => {
  console.error(`Error: ${error.message}`);

  // عند الحجب أو الفشل: اطبع ما جُرّب وماذا ردّ كل مصدر.
  for (const attempt of error.attempts ?? []) {
    console.error(`  ${attempt.source}: ${attempt.detail}`);
  }

  process.exit(error instanceof CaptionError ? 2 : 1);
});
